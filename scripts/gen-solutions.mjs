// Precomputes one clean route for every shipped plan (lessons, campaign, annex, Black Archive and the Last Heist
// opening vault, version 0) with tests/solve.cjs: no EMP, ghost rules. Writes src/solutions.js, which the game uses
// for WATCH SOLUTION, the "all levels solved" list and the Last Heist HOUSE RUN. Nothing is solved at runtime.
// Also writes src/daily-solutions.js: one clean route per Daily Heist plan (src/daily-levels.js), same rules.
// Re-run after any level change:   node scripts/gen-solutions.mjs
// tests/solutions.test.cjs fails when a stored route no longer wins (a level changed without regenerating).
import {createRequire} from 'node:module';import {writeFileSync} from 'node:fs';import {fileURLToPath} from 'node:url';import path from 'node:path';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url))),require=createRequire(import.meta.url);
const levels=require('../src/cutaway-levels.js'),E=require('../src/engine.js'),{solve}=require('../tests/solve.cjs');
const out={};let longest=0;
for(const l of levels){
 const r=solve(l,{maxNodes:900000});if(!r.ok)throw Error('No clean route found for '+l.id+' ('+r.expanded+' nodes)');
 const q=E.replay(E.normalize(l),r.actions,'ghost');if(!q.ok||q.state.empUsed)throw Error('Route for '+l.id+' does not replay as a clean win');
 out[l.id]={actions:r.actions,turns:r.turns};longest=Math.max(longest,r.turns);console.log(l.id.padEnd(14),String(r.turns).padStart(3),'turns');
}
const body=Object.entries(out).map(([id,s])=>' '+JSON.stringify(id)+':{"turns":'+s.turns+',"actions":'+JSON.stringify(s.actions)+'}').join(',\n');
const text=`/* GENERATED by scripts/gen-solutions.mjs from src/cutaway-levels.js with tests/solve.cjs. Do not edit by hand.
   One clean route per shipped plan (no EMP, ghost rules): a witness that the level can be cleared, not a shortest-path
   claim. tests/solutions.test.cjs replays every route with the current engine. ${Object.keys(out).length} plans, longest ${longest} turns. */
(function(root){const solutions=Object.freeze({
${body}
});if(typeof module==='object'&&module.exports)module.exports=solutions;else root.HEIST_SOLUTIONS=solutions;})(globalThis);
`;
writeFileSync(path.join(root,'src','solutions.js'),text);console.log('Wrote src/solutions.js:',Object.keys(out).length,'plans');

// Daily Heist plans: a separate file, so the campaign bundle does not carry them.
const daily=require('../src/daily-levels.js'),dout={};let dlong=0;
for(const l of daily){
 const r=solve(l,{maxNodes:900000});if(!r.ok)throw Error('No clean route found for '+l.id+' ('+r.expanded+' nodes)');
 const q=E.replay(E.normalize(l),r.actions,'ghost');if(!q.ok||q.state.empUsed)throw Error('Route for '+l.id+' does not replay as a clean win');
 dout[l.id]={actions:r.actions,turns:r.turns};dlong=Math.max(dlong,r.turns);console.log(l.id.padEnd(14),String(r.turns).padStart(3),'turns');
}
const dbody=Object.entries(dout).map(([id,s])=>' '+JSON.stringify(id)+':{"turns":'+s.turns+',"actions":'+JSON.stringify(s.actions)+'}').join(',\n');
writeFileSync(path.join(root,'src','daily-solutions.js'),`/* GENERATED by scripts/gen-solutions.mjs from src/daily-levels.js with tests/solve.cjs. Do not edit by hand.
   One clean route per Daily Heist plan (no EMP, ghost rules): a witness that the level can be cleared, not the best
   route (each plan records its exact minimum as "best"). tests/solutions.test.cjs replays every route. ${Object.keys(dout).length} plans, longest ${dlong} turns. */
(function(root){const solutions=Object.freeze({
${dbody}
});if(typeof module==='object'&&module.exports)module.exports=solutions;else root.HEIST_DAILY_SOLUTIONS=solutions;})(globalThis);
`);console.log('Wrote src/daily-solutions.js:',Object.keys(dout).length,'plans');
